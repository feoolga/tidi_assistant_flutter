// lib/domain/models/rag_document_status.dart

/// Статус **отдельного** документа в RAG-наборе.
///
/// Отличается от [RagStatus] (статуса **набора**):
/// - [RagStatus] — **агрегат** по всем документам, вычисляется
///   на бэкенде на чтение;
/// - [RagDocumentStatus] — статус **одного** документа,
///   хранится в БД (`documents.status`).
///
/// **Жизненный цикл документа:**
/// ```
///   pending → processing → success
///                       ↘ failed
/// ```
/// Документ **не может** вернуться назад (например, `success` → `pending`).
/// Если пользователь удалит и загрузит файл заново — это **новый**
/// документ с **новым** id, а не смена статуса старого.
///
/// **Клиентских статусов здесь НЕТ.** Фаза «загрузка байтов на сервер»
/// (`uploading`) — это часть клиентского процесса `RagCreationState`,
/// а **не** статус документа на бэкенде. Сервер узнаёт о документе
/// только когда **все** байты уже у него.
enum RagDocumentStatus {
  /// Документ **в очереди** на обработку.
  ///
  /// Байты получены сервером, строка в БД создана, но воркер ещё
  /// не начал обработку (например, все воркеры заняты).
  ///
  /// В UI: иконка «часы»/«⏳», серый цвет, статус «в очереди».
  pending,

  /// Документ **обрабатывается прямо сейчас**.
  ///
  /// Воркер разбирает файл через docling (парсинг, чанкинг),
  /// потом считает векторы через bge-m3, потом пишет в OpenSearch.
  /// Может занимать от секунд (маленький `.txt`) до минут
  /// (большой скан PDF с OCR).
  ///
  /// В UI: иконка «спиннер»/«🔄», синий или нейтральный цвет,
  /// статус «обрабатывается».
  processing,

  /// Документ **успешно проиндексирован**.
  ///
  /// Все чанки лежат в OpenSearch, доступны для поиска через
  /// `agentic_rag`. Можно использовать в чате.
  ///
  /// В UI: иконка «галочка»/«✅», зелёный цвет, статус «готов».
  success,

  /// Документ **упал при обработке**.
  ///
  /// Причина — в поле [RagDocument.error]. Возможные причины:
  /// невалидный формат, ошибка docling, ошибка эмбеддинга, ошибка
  /// записи в OpenSearch. См. `documents.error` в схеме БД.
  ///
  /// Документ можно **удалить** и загрузить заново — повторная
  /// попытка индексации **не предусмотрена** (это не «retry»,
  /// это «новый документ»).
  ///
  /// В UI: иконка «крестик»/«❌», красный цвет, статус «ошибка»,
  /// рядом — кнопка «удалить».
  failed,
}
