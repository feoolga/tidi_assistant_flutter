// lib/domain/models/rag_document.dart

import '../../core/utils/copy_with_marker.dart';
import 'rag_document_status.dart';

/// Документ внутри RAG-набора.
///
/// Одна запись из таблицы `documents` на бэкенде. Соответствует
/// элементу из `GET .../documents` или `POST .../documents`.
///
/// **Что тут НЕТ по сравнению с БД.** В таблице `documents` есть поля
/// `content_hash`, `storage_key`, `source_bucket`, `origin`,
/// `origin_ref` — мы их **не тащим** в домен. Причины:
/// - `content_hash` — внутренняя дедупликация, клиенту не нужен;
/// - `storage_key` — путь в SeaweedFS, утечка внутренней структуры;
/// - `source_bucket` — только для импорта из бакета, в UI не показываем;
/// - `origin` / `origin_ref` — служебное поле, обычному пользователю
///   не нужно (см. ответ бэкендера: «Служебное... Обычному
///   пользователю не нужно»).
///
/// **Про `origin` (принцип YAGNI).** Если в будущем понадобится —
/// добавим **точечно** (поле в модели + обработка в маппере). Сейчас
/// **не тащим**, потому что:
/// - UI его **не показывает**;
/// - **не** знаем точный список значений (в README и в ответе
///   бэкендера — разные);
/// - добавление **позже** — 30 минут работы.
///
/// **Если** сервер присылает `origin` в JSON — DTO (D2) его
/// **просто игнорирует**. Dart не падает от лишних полей в JSON.
class RagDocument {
  // ============================================================
  // 1. ИДЕНТИФИКАЦИЯ
  // ============================================================

  /// ID документа в наборе (UUID, генерируется на бэкенде).
  final String id;

  /// Имя файла — как его видит пользователь.
  ///
  /// Бэкенд **санитизирует** имена (см. README ingestion-сервиса,
  /// раздел «Загрузка архивом и импорт»): `../../etc/passwd`
  /// превратится в `passwd`, коллизии после «сплющивания»
  /// разводятся суффиксом. Значит, `filename` **безопасен** для
  /// отображения.
  final String filename;

  // ============================================================
  // 2. МЕТАДАННЫЕ
  // ============================================================

  /// Размер файла в байтах.
  ///
  /// Приходит от сервера **как есть**. Для отображения —
  /// форматируем в UI (КБ/МБ).
  final int sizeBytes;

  /// Когда документ был создан (то есть загружен в набор).
  ///
  /// **Почему `DateTime`, а не `String`:** домен работает с типами,
  /// не со строками. Парсинг из ISO-8601 — работа маппера (D2).
  final DateTime createdAt;

  // ============================================================
  // 3. СОСТОЯНИЕ
  // ============================================================

  /// Текущий статус обработки. См. [RagDocumentStatus].
  ///
  /// Жизненный цикл: `pending → processing → success / failed`.
  /// Обратный переход невозможен.
  final RagDocumentStatus status;

  /// Сколько **чанков** документ породил после разбиения.
  ///
  /// `0` — нормально для `pending` / `processing` (обработка
  /// не завершена) и для `failed` (документ не разбился).
  /// Для `success` — сколько реально лежит в OpenSearch.
  final int chunksCount;

  /// Текст ошибки — **только** при `status: failed`. Иначе `null`.
  ///
  /// **Почему `String?`, а не объект.** В схеме БД `documents.error` —
  /// это **текстовое** поле, не JSON. Мы не знаем структуру ошибки,
  /// потому что её нет. Если бэкендер завтра добавит структуру —
  /// доработаем **точечно**.
  ///
  /// **Для UI:** показываем `error` в детальной карточке документа
  /// или в tooltip. Не парсим, не форматируем — как есть.
  final String? error;

  // ============================================================
  // 4. ДЕДУПЛИКАЦИЯ
  // ============================================================

  /// ID «старшего» документа, если текущий — **дубликат**.
  ///
  /// Заполнено, когда пользователь загрузил файл, **уже**
  /// существующий в наборе (совпадение по `content_hash`).
  /// В этом случае **новый** документ **не создаётся** — сервер
  /// возвращает **существующий** с заполненным `duplicateOf`.
  ///
  /// **Особый случай:** может быть равен `id` (сервер вернул
  /// существующий документ под его собственным id, а не под
  /// новым). На это **не полагаемся** — считаем признаком дубликата
  /// **только** `duplicateOf != null`.
  ///
  /// **Что это значит для UI:** показать пользователю «файл уже
  /// был в наборе». **Не ошибка** — а информация.
  ///
  /// **`null`** — обычный документ, не дубликат.
  final String? duplicateOf;

  // ============================================================
  // 5. КОНСТРУКТОР
  // ============================================================

  const RagDocument({
    required this.id,
    required this.filename,
    required this.sizeBytes,
    required this.createdAt,
    required this.status,
    this.chunksCount = 0,
    this.error,
    this.duplicateOf,
  });

  // ============================================================
  // 6. ГЕТТЕРЫ
  // ============================================================

  /// Готов ли документ к использованию?
  bool get isReady => status == RagDocumentStatus.success;

  /// Упал ли документ?
  bool get isFailed => status == RagDocumentStatus.failed;

  /// В работе — `pending` или `processing`.
  ///
  /// Удобно для UI: показывать спиннер для обоих статусов.
  bool get isInProgress =>
      status == RagDocumentStatus.pending ||
      status == RagDocumentStatus.processing;

  /// Это дубликат уже существующего документа?
  ///
  /// **Не полагаемся на `duplicateOf == id`** — только на `!= null`.
  bool get isDuplicate => duplicateOf != null;

  // ============================================================
  // 7. КОПИРОВАНИЕ
  // ============================================================

  /// Создать копию с изменёнными полями.
  ///
  /// **Пока не используется активно** — но нужен для **оптимистичных
  /// обновлений** в UI: например, пользователь удалил документ,
  /// UI **сразу** убирает его из списка (до ответа сервера).
  /// Если сервер вернёт ошибку — откатываем через `copyWith`.
  ///
  /// **Nullable-поля** (`error`, `duplicateOf`) используют маркер
  /// [copyWithUnset] — чтобы отличать «не передали» от «передали
  /// `null`». Пример: `copyWith(error: null)` **сбрасывает** ошибку.
  RagDocument copyWith({
    String? id,
    String? filename,
    int? sizeBytes,
    DateTime? createdAt,
    RagDocumentStatus? status,
    int? chunksCount,
    Object? error = copyWithUnset,
    Object? duplicateOf = copyWithUnset,
  }) {
    return RagDocument(
      id: id ?? this.id,
      filename: filename ?? this.filename,
      sizeBytes: sizeBytes ?? this.sizeBytes,
      createdAt: createdAt ?? this.createdAt,
      status: status ?? this.status,
      chunksCount: chunksCount ?? this.chunksCount,
      error: isCopyWithUnset(error) ? this.error : error as String?,
      duplicateOf: isCopyWithUnset(duplicateOf)
          ? this.duplicateOf
          : duplicateOf as String?,
    );
  }

  // ============================================================
  // 8. ОТЛАДКА
  // ============================================================

  @override
  String toString() {
    return 'RagDocument(id: $id, filename: "$filename", '
        'sizeBytes: $sizeBytes, status: $status, '
        'chunksCount: $chunksCount)';
  }
}
