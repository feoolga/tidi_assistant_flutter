/// Счётчики документов в RAG-наборе — по статусам.
///
/// Соответствует полю `documents` в ответе `GET /v1/platform/rags/{id}`:
/// ```json
/// "documents": {"total": 3, "ready": 1, "failed": 0, "pending": 2}
/// ```
///
/// **Про `pending` — важная тонкость.** В **счётчиках** поле `pending`
/// означает «**не завершено**» — то есть включает **и** `pending`,
/// **и** `processing` документы. Это **не** то же самое, что
/// [RagDocumentStatus.pending] у отдельного документа (там — только
/// «в очереди, воркер ещё не взял»).
///
/// Почему так: сервер **объединяет** `pending` и `processing`
/// в один счётчик, потому что пользователю **неважно** различие
/// («не готово» — и точка). Для UI это **удобно**.
class DocumentsCounts {
  /// Всего документов в наборе.
  ///
  /// Складывается из: `ready + failed + pending`.
  final int total;

  /// Сколько документов **успешно** проиндексировано (`success`).
  final int ready;

  /// Сколько документов **упало** (`failed`).
  final int failed;

  /// Сколько документов **не завершено** — включает `pending`
  /// **и** `processing`.
  final int pending;

  const DocumentsCounts({
    this.total = 0,
    this.ready = 0,
    this.failed = 0,
    this.pending = 0,
  });

  /// Пустые счётчики — набор без документов.
  factory DocumentsCounts.empty() => const DocumentsCounts();

  // ------------------------------------------------------------
  // Производные свойства
  // ------------------------------------------------------------

  /// Есть ли хотя бы один документ.
  bool get isEmpty => total == 0;

  /// Все ли документы **готовы**?
  ///
  /// `true`, если есть документы и **все** в статусе `ready`.
  /// Пустой набор **не** считается «завершённым» — там **нечего**
  /// завершать.
  bool get isComplete => total > 0 && ready == total;

  /// Есть ли **упавшие** документы?
  ///
  /// Для UI — например, чтобы показать плашку «часть файлов не
  /// удалось обработать».
  bool get hasFailures => failed > 0;

  /// Прогресс в **процентах** (0…100) — для прогресс-бара.
  ///
  /// Считаем как `ready / total`. **Упавшие не считаем** как готовые:
  /// они **не** будут доступны в чате. Значит, при `ready = 3`,
  /// `failed = 2`, `pending = 0`, `total = 5` — прогресс **60%**,
  /// а не 100%.
  ///
  /// Если документов нет — возвращаем `0`.
  int get readyPercent {
    if (total == 0) return 0;
    return ((ready / total) * 100).round();
  }

  @override
  String toString() =>
      'DocumentsCounts(total: $total, ready: $ready, '
      'failed: $failed, pending: $pending)';
}

// ============================================================
// 2. RAG-НАБОР
// ============================================================

/// RAG-набор — контейнер документов.
///
/// Одна запись из таблицы `rag_sets` на бэкенде. Соответствует
/// элементу из `GET /v1/platform/rags` или `POST /v1/platform/rags`.
///
/// **Что тут НЕТ:**
/// - **`List<RagDocument>`** — документы **не** тащим в набор.
///   Они — **отдельный** запрос (`GET .../documents`), могут быть
///   большими, и **не нужны** на каждом экране списка. Если
///   понадобятся — отдельный провайдер `ragDocumentsProvider(ragId)`.
/// - **`ownerId`** — SSOT владельца — **сервер** (в `X-User-Id`).
///   В домене **не нужен**: все наши наборы — наши.
/// - **`deletedAt`** — soft-delete. Если набор удалён, он **не
///   приходит** в API. В домене не нужно.
/// - **`iconUrl`** — иконка отдаётся **отдельным** эндпойнтом
///   (`GET .../icon`), в списке — только флаг [hasIcon]. Иначе
///   список наборов был бы **тяжёлым**.
class RagSet {
  // ============================================================
  // 2.1. ИДЕНТИФИКАЦИЯ
  // ============================================================

  /// ID набора (UUID, генерируется на бэкенде).
  final String id;

  /// Название набора. Обязательное, 1–200 символов.
  ///
  /// Пользователь задаёт при создании, может переименовать через
  /// `PATCH /v1/platform/rags/{id}`.
  final String name;

  /// Описание набора (опционально).
  ///
  /// Свободный текст. Бэкендер лимит **не** называл — ставим
  /// разумное ограничение в UI (2000 символов).
  final String? description;

  // ============================================================
  // 2.2. СОСТОЯНИЕ
  // ============================================================

  /// Статус набора. См. [RagStatus].
  ///
  /// **Вычисляется на бэкенде** как **агрегат** по документам
  /// (см. README ingestion-сервиса, раздел «Статус набора —
  /// производная»). Не хранится в БД.
  final RagStatus status;

  /// Счётчики документов — total / ready / failed / pending.
  ///
  /// См. [DocumentsCounts]. **`pending` здесь включает
  /// `processing`** — не путать со статусом отдельного документа.
  final DocumentsCounts documentsCounts;

  /// **Общее** число чанков по всем документам набора.
  ///
  /// Складывается из `chunksCount` каждого документа.
  /// Если `0` при `status: ready` — что-то странное, но бывает.
  final int chunksTotal;

  /// Есть ли документы в **не завершённом** состоянии?
  ///
  /// **Отдельное поле от `documentsCounts.pending > 0`.** Сервер
  /// сам решает, что считать «pending» — возможно, учитывает
  /// что-то, чего нет в счётчиках.
  ///
  /// **Используется `RagStatusPoller` (D5)** — пока `hasPending ==
  /// true`, продолжаем опрашивать статус. Когда `false` —
  /// останавливаемся.
  final bool hasPending;

  // ============================================================
  // 2.3. ИКОНКА
  // ============================================================

  /// Есть ли у набора **иконка**.
  ///
  /// **Не URL, не путь** — просто флаг. Иконка отдаётся
  /// отдельным эндпойнтом `GET .../icon`. В списке наборов
  /// тащить все иконки — **слишком тяжело**.
  final bool hasIcon;

  // ============================================================
  // 2.4. КОНФИГУРАЦИЯ
  // ============================================================

  /// Конфиг набора — настройки генерации. См. [RagConfig].
  ///
  /// Весь конфиг — **query-time** (применяется при запросе, не при
  /// индексации). Поэтому **переиндексация не нужна** — любая
  /// правка применяется со следующего сообщения.
  final RagConfig config;

  // ============================================================
  // 2.5. ДАТЫ
  // ============================================================

  /// Когда набор создан.
  final DateTime createdAt;

  /// Когда набор последний раз обновлялся.
  ///
  /// Меняется при: создании, переименовании, добавлении/удалении
  /// документа, обновлении конфига, обновлении иконки.
  ///
  /// **Для UI:** сортировка списка наборов — по `updatedAt`.
  final DateTime updatedAt;

  // ============================================================
  // 2.6. КОНСТРУКТОР
  // ============================================================

  const RagSet({
    required this.id,
    required this.name,
    this.description,
    required this.status,
    required this.documentsCounts,
    this.chunksTotal = 0,
    this.hasPending = false,
    this.hasIcon = false,
    required this.config,
    required this.createdAt,
    required this.updatedAt,
  });

  // ============================================================
  // 2.7. ГЕТТЕРЫ
  // ============================================================

  /// Готов ли набор к использованию (можно задавать вопросы)?
  ///
  /// **Важно:** `ready` наступает, когда **хотя бы один** документ
  /// проиндексирован. Могут быть **ещё** обрабатывающиеся и
  /// упавшие — это **нормально**. См. README ingestion-сервиса.
  bool get isReady => status == RagStatus.ready;

  /// Идёт ли индексация?
  bool get isIngesting => status == RagStatus.ingesting;

  /// Набор пуст (нет документов)?
  bool get isEmpty => status == RagStatus.empty;

  /// Все документы упали?
  bool get isFailed => status == RagStatus.failed;

  // ============================================================
  // 2.8. КОПИРОВАНИЕ
  // ============================================================

  /// Создать копию с изменёнными полями.
  ///
  /// **`description` использует маркер [copyWithUnset]** — потому что
  /// это **nullable**-поле. Нужно уметь отличать «не передали»
  /// от «передали `null`» (сбросить).
  ///
  /// **Используется в `RagStatusPoller` (D5).** Каждый опрос статуса
  /// приносит **новый** `RagSet` — но **не все** поля меняются
  /// (например, `name` то же). Poller может **мержить** изменения
  /// через `copyWith`, чтобы не терять локальные данные.
  RagSet copyWith({
    String? id,
    String? name,
    Object? description = copyWithUnset,
    RagStatus? status,
    DocumentsCounts? documentsCounts,
    int? chunksTotal,
    bool? hasPending,
    bool? hasIcon,
    RagConfig? config,
    DateTime? createdAt,
    DateTime? updatedAt,
  }) {
    return RagSet(
      id: id ?? this.id,
      name: name ?? this.name,
      description: isCopyWithUnset(description)
          ? this.description
          : description as String?,
      status: status ?? this.status,
      documentsCounts: documentsCounts ?? this.documentsCounts,
      chunksTotal: chunksTotal ?? this.chunksTotal,
      hasPending: hasPending ?? this.hasPending,
      hasIcon: hasIcon ?? this.hasIcon,
      config: config ?? this.config,
      createdAt: createdAt ?? this.createdAt,
      updatedAt: updatedAt ?? this.updatedAt,
    );
  }

  // ============================================================
  // 2.9. ОТЛАДКА
  // ============================================================

  @override
  String toString() {
    return 'RagSet(id: $id, name: "$name", status: $status, '
        'documents: $documentsCounts, hasPending: $hasPending)';
  }
}
