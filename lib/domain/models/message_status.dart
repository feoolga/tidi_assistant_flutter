// lib/domain/models/message_status.dart

/// Статус сообщения — по данным сервера.
///
/// **Зачем нужен.** В `GET .../messages` сервер отдаёт поле `status`
/// у каждого сообщения (см. README Agentic RAG, раздел
/// «GET .../messages»). Значения:
/// - `"ok"` — успешно обработано;
/// - `"failed"` — генерация упала (например, `client_disconnected`
///   при обрыве SSE-стрима клиентом);
/// - `"pending"` — ещё обрабатывается (обычно не приходит
///   в историю, но на всякий случай).
///
/// **Почему отдельный enum, а не строка.**
/// - **Type safety.** Опечатку `"faild"` не поймает `String`,
///   а `MessageStatus.faild` не скомпилируется.
/// - **Exhaustive switch.** Dart 3 требует обработать **все**
///   случаи enum — пропустить `pending` нельзя.
/// - **Самодокументируемость.** Все возможные состояния — в одном
///   месте.
///
/// **Где используется.** `Message.status`, `MessageMapper`,
/// `MessageBubble` (для показа «Не удалось получить ответ»).
enum MessageStatus {
  /// Сообщение успешно обработано.
  ///
  /// **Дефолт для случая «status не пришёл».** Это безопасно:
  /// `document_chat` **не** присылает `status` (у него своя схема),
  /// и все его сообщения — по факту `ok`. Для `agentic_rag`
  /// `status` **всегда** приходит (`ok`/`failed`).
  ok,

  /// Генерация упала — сервер не смог получить ответ.
  ///
  /// **Типичный случай:** `error == "client_disconnected"` — клиент
  /// отвалился от SSE-стрима (Wi-Fi, kill приложения). Сервер
  /// **прервал** генерацию и сохранил сообщение с пустым `content`.
  ///
  /// **Что видит пользователь:** пустой пузырь AI. UI **должен**
  /// показать пометку «Не удалось получить ответ» — иначе непонятно,
  /// что произошло.
  failed,

  /// Сообщение ещё обрабатывается.
  ///
  /// Обычно не приходит в историю (`GET .../messages` возвращает
  /// только завершённые ходы), но на всякий случай различаем.
  pending,
}
