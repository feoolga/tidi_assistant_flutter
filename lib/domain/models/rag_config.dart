// lib/domain/models/rag_config.dart

import '../../core/utils/copy_with_marker.dart';

/// Конфигурация RAG-набора — настройки, влияющие на **генерацию ответов**.
///
/// **Что сюда входит.** Только **query-time** параметры — те, что
/// применяются в момент запроса пользователя, а не при индексации.
/// Поэтому **переиндексация при смене конфига не нужна** — любая
/// правка применяется со следующего сообщения (см. README
/// ingestion-сервиса, раздел «Конфиг набора»).
///
/// **Что сюда НЕ входит:**
/// - `name`, `description` — это про набор, не про генерацию;
/// - системный промпт агента — он платформенный, пользователю
///   недоступен (см. поле [prompt] ниже);
/// - промпты rewriter / multi-query / eval — тоже платформенные.
///
/// **Дефолты** совпадают с бэкендом (см. `ingest.env.example`).
/// Если бэкендер поменяет дефолты — поменяем **только здесь**.
class RagConfig {
  // ============================================================
  // 1. ПОЛЯ
  // ============================================================

  /// Дополнительные инструкции для LLM.
  ///
  /// **Дополняет** системный промпт агента отдельным блоком,
  /// **не заменяет** его. Иначе пользователь одной формулировкой
  /// снёс бы требования к цитированию и структурированному выводу,
  /// и генерация начала бы отдавать невалидный JSON (см. README
  /// ingestion-сервиса, раздел «Конфиг набора»).
  ///
  /// `null` — дополнений нет, работает только системный промпт.
  ///
  /// **Лимит бэкенда** — до 4000 символов. Мы его **не проверяем**
  /// в конструкторе (это валидация для UI-формы), но если строка
  /// окажется слишком длинной — бэкенд вернёт `400`.
  final String? prompt;

  /// «Температура» генерации — чем выше, тем креативнее.
  ///
  /// Применяется **только к финальному ответу**. У rewriter и eval
  /// температура захардкожена в `0.0` — это детерминированные шаги
  /// планировщика, и пользователь не должен ломать себе разбор
  /// запроса (см. README ingestion-сервиса).
  ///
  /// **Допустимый диапазон:** 0.0…1.0 (проверяется бэкендом,
  /// `CHECK`-ограничением в БД).
  final double temperature;

  /// Сколько **фрагментов** поднимать из индекса.
  ///
  /// Пул растёт как `topK × 3 ветки × N вариантов multi-query × итерации`
  /// (см. README ingestion-сервиса). Поэтому `topK` — не «сколько
  /// попадёт в ответ», а «сколько поднять»; фильтрация идёт дальше
  /// на стороне агента.
  ///
  /// **Допустимый диапазон:** 1…10 (проверяется бэкендом).
  /// Потолок 10 — не вкусовщина: он ограничивает размер контекста,
  /// уходящего в eval агентного цикла.
  final int topK;

  /// Порог косинусного сходства для фильтрации kNN-ветки.
  ///
  /// Значение **в терминах косинуса** (понятная пользователю величина),
  /// хотя внутренне OpenSearch использует `_score = 1 / (1 + cosineDistance)`.
  /// Пересчёт — на стороне бэкенда.
  ///
  /// **Допустимый диапазон:** 0.0…1.0 (проверяется бэкендом).
  ///
  /// **Важно:** порог применяется **только к kNN-ветке** и **до**
  /// фьюжна. BM25 и `rank_features` режутся по `topK`.
  /// Так устроен гибридный поиск — см. README ingestion-сервиса,
  /// раздел «Шкала скоров и score_threshold».
  final double scoreThreshold;

  // ============================================================
  // 2. КОНСТРУКТОР
  // ============================================================

  /// Создать конфигурацию RAG-набора.
  ///
  /// **Дефолты** совпадают с бэкендом:
  /// - `temperature: 0.3`,
  /// - `topK: 5`,
  /// - `scoreThreshold: 0.4`,
  /// - `prompt: null`.
  ///
  /// **Assert-проверки** — только для **разработки**. В релизных
  /// сборках `assert` отключён, поэтому **нулевой** overhead.
  ///
  /// **Почему `assert`, а не `throw`.** Эти значения — из **нашего**
  /// кода (дефолты или форма UI), а не с сервера. Если разработчик
  /// передал мусор — это **баг в коде**, и он **должен** упасть
  /// в дебаге. В проде — сервер сам провалидирует и вернёт `400`.
  ///
  /// **Что с данными с сервера.** Если сервер пришлёт некорректные
  /// значения (баг бэкенда) — их **не** пропустит **маппер** (D2),
  /// а не этот конструктор. Здесь мы **не защищаемся** от сервера —
  /// только от своих ошибок.
  const RagConfig({
    this.prompt,
    this.temperature = 0.3,
    this.topK = 5,
    this.scoreThreshold = 0.4,
  }) : assert(
         temperature >= 0.0 && temperature <= 1.0,
         'temperature должен быть в диапазоне 0.0…1.0, '
         'получено: $temperature',
       ),
       assert(
         topK >= 1 && topK <= 10,
         'topK должен быть в диапазоне 1…10, получено: $topK',
       ),
       assert(
         scoreThreshold >= 0.0 && scoreThreshold <= 1.0,
         'scoreThreshold должен быть в диапазоне 0.0…1.0, '
         'получено: $scoreThreshold',
       );

  // ============================================================
  // 3. КОПИРОВАНИЕ
  // ============================================================

  /// Создать копию с изменёнными полями.
  ///
  /// **`prompt` использует маркер [copyWithUnset]** — потому что
  /// это **nullable**-поле. Нужно уметь отличать «не передали»
  /// (оставить как было) от «передали `null`» (сбросить в `null`).
  ///
  /// Примеры:
  /// - `copyWith()` — копия без изменений;
  /// - `copyWith(prompt: 'Отвечай кратко')` — установить промпт;
  /// - `copyWith(prompt: null)` — **сбросить** промпт в `null`;
  /// - `copyWith(temperature: 0.7)` — изменить температуру.
  RagConfig copyWith({
    Object? prompt = copyWithUnset,
    double? temperature,
    int? topK,
    double? scoreThreshold,
  }) {
    return RagConfig(
      prompt: isCopyWithUnset(prompt) ? this.prompt : prompt as String?,
      temperature: temperature ?? this.temperature,
      topK: topK ?? this.topK,
      scoreThreshold: scoreThreshold ?? this.scoreThreshold,
    );
  }

  // ============================================================
  // 4. ОТЛАДКА
  // ============================================================

  @override
  String toString() {
    return 'RagConfig(prompt: ${prompt == null ? "null" : "${prompt!.length} chars"}, '
        'temperature: $temperature, topK: $topK, '
        'scoreThreshold: $scoreThreshold)';
  }
}
