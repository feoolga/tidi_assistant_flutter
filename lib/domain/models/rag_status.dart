// lib/domain/models/rag_status.dart

/// Статус RAG-набора.
///
/// Это **доменный** статус — вычисляется на бэкенде как **агрегат**
/// по документам набора (см. README ingestion-сервиса, раздел
/// «Статус набора — производная»). Не хранится в БД.
///
/// **Логика вычисления (на бэкенде):**
/// - `documents_total == 0` → [empty];
/// - есть хоть один `success` → [ready] (даже если часть ещё в работе);
/// - нет `success`, есть `pending`/`processing` → [ingesting];
/// - нет `success`, все `failed` → [failed].
///
/// **Почему `ready` при частичной готовности:** чат уже осмыслен
/// на том, что проиндексировано. Прогресс UI показывает отдельно —
/// через счётчики документов.
enum RagStatus {
  /// В наборе **нет документов**.
  ///
  /// Пользователь создал набор, но ещё ничего не загрузил
  /// (или загрузил, но все — дубликаты существующих).
  empty,

  /// Идёт **индексация** документов.
  ///
  /// Хотя бы один документ в статусе `pending`/`processing`.
  /// Документов `ready` пока нет.
  ingesting,

  /// Набор **готов к использованию**.
  ///
  /// Хотя бы один документ успешно проиндексирован. Может быть,
  /// часть ещё в работе или упала — но чат уже осмыслен.
  ready,

  /// **Все** документы упали при индексации.
  ///
  /// Ни одного успешного. Набор непригоден для использования.
  failed,
}
