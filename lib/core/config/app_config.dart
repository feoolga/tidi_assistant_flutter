// lib/core/config/app_config.dart

import 'package:flutter_dotenv/flutter_dotenv.dart';

/// Конфигурация приложения.
///
/// Здесь хранятся все настройки в одном месте.
/// Если нужно поменять URL сервера, таймауты или лимиты — меняем только здесь.
///
/// **Принцип группировки:**
/// - разделы **1–4** — общие для всего приложения;
/// - раздел **5** — идентификаторы агентов;
/// - раздел **6** — лимиты сценария `document_chat` (чат с файлами);
/// - раздел **7** — лимиты RAG-сценария (пользовательские наборы).
///
/// **Почему лимиты разделены по сценариям:**
/// У `document_chat` и RAG **разные** требования: файл 25 МБ vs 200 МБ,
/// 5 файлов в сообщении vs 10 в пачке, форматы PDF/JPG/PNG vs более
/// широкий список. Если смешать — получим константу `maxFileSizeBytes`,
/// по которой непонятно, какой из двух лимитов имеется в виду.
class AppConfig {
  // ============================================================
  // 1. БАЗОВЫЙ URL СЕРВЕРА
  // ============================================================

  // ---- 1. БАЗОВЫЙ URL ----
  static String get baseUrl {
    final url = dotenv.env['API_URL'];
    if (url == null || url.isEmpty) {
      throw Exception('API_URL не задан в .env файле');
    }
    return url;
  }

  // ============================================================
  // 2. ПОЛЬЗОВАТЕЛЬ (пока временно)
  // ============================================================

  // ---- 2. ID ПОЛЬЗОВАТЕЛЯ ----
  static String get userId {
    final id = dotenv.env['USER_ID'];
    if (id == null || id.isEmpty) {
      throw Exception('USER_ID не задан в .env файле');
    }
    return id;
  }

  // ============================================================
  // 3. ТАЙМАУТЫ
  // ============================================================

  /// Таймаут для обычных запросов (10 секунд).
  static const Duration timeout = Duration(seconds: 10);

  /// Таймаут для стримов (дольше, так как ответ может идти долго).
  static const Duration streamTimeout = Duration(seconds: 60);

  /// Таймаут для загрузки одного файла в `document_chat`.
  ///
  /// Отдельный и очень длинный, потому что бэкенд (`document_chat`)
  /// синхронно прогоняет файл через MinerU (OCR + разбор в markdown).
  /// По README бэкендера — `MINERU_TIMEOUT_SECONDS=600` по умолчанию.
  /// Ставим те же 10 минут, чтобы наш таймаут не сработал раньше серверного.
  static const Duration uploadTimeout = Duration(minutes: 10);

  /// Таймаут на **создание** RAG-набора.
  ///
  /// Обычная лёгкая операция: создать запись в Postgres.
  /// Много времени не нужно, но и слишком мало нельзя —
  /// база может отвечать медленно под нагрузкой. 30 секунд — с запасом.
  static const Duration ragCreateTimeout = Duration(seconds: 30);

  /// Таймаут на загрузку **пачки** документов в RAG-набор.
  ///
  /// В отличие от `uploadTimeout` (один файл, 10 минут), здесь может
  /// быть до `ragMaxFilesPerBatch` файлов (10 штук по 200 МБ = 2 ГБ).
  ///
  /// **Почему 15 минут:**
  /// 2 ГБ на 4G со скоростью ~5 МБ/с — это около 7 минут только на
  /// передачу. Плюс обработка первого файла (сервер начинает
  /// обрабатывать, пока другие ещё грузятся). 15 минут — с запасом.
  ///
  /// **Почему не `uploadTimeout * 10`:** линейно не масштабируется.
  /// Если сервер обрабатывает файлы параллельно (а он, судя по README,
  /// использует воркеры), время растёт нелинейно.
  static const Duration ragUploadTimeout = Duration(minutes: 15);

  // ============================================================
  // 4. ЗАГОЛОВКИ ПО УМОЛЧАНИЮ
  // ============================================================

  /// Заголовки, которые отправляются с каждым запросом.
  static const Map<String, String> defaultHeaders = {
    'Content-Type': 'application/json',
    'Accept': 'application/json',
  };

  /// Заголовки для стримов (SSE).
  static const Map<String, String> streamHeaders = {
    'Content-Type': 'application/json',
    'Accept': 'text/event-stream',
  };

  // ============================================================
  // 5. ИДЕНТИФИКАТОРЫ АГЕНТОВ
  // ============================================================

  /// ID агента для RAG-сценария.
  ///
  /// **Важно:** это **не** `rag/<uuid>`. Это **id агента** в реестре
  /// мастера — тот же самый для **всех** RAG-наборов. Набор задаётся
  /// отдельно через поле `model` в теле запроса (`rag/<uuid набора>`).
  ///
  /// Используется в путях:
  /// - `POST /agents/agentic_rag/v1/platform/conversations` — создать чат;
  /// - `GET  /agents/agentic_rag/v1/chat/completions/{id}/sources`;
  /// - `POST /agents/agentic_rag/v1/chat/completions/{id}/feedback`.
  ///
  /// **Почему константа:** это «магическая строка», которая должна
  /// совпадать с реестром мастера. Если бэкендер переименует агента —
  /// поменяем здесь **одно** место.
  static const String ragAgentId = 'agentic_rag';

  /// Префикс для поля `model` в теле `POST /v1/responses` для RAG.
  ///
  /// Схема: `model = ragModelPrefix + ragId`.
  /// Пример: `rag/22222222-2222-2222-2222-222222222222`.
  static const String ragModelPrefix = 'rag/';

  /// Собрать значение `model` для RAG-запроса.
  ///
  /// **Зачем метод:** чтобы не собирать строку в 5 местах через
  /// конкатенацию. Если бэкендер поменяет формат (например,
  /// `rag_set/<uuid>`) — правка в одном месте.
  ///
  /// Пример:
  /// ```dart
  /// AppConfig.ragModelId('22222222-...') // → 'rag/22222222-...'
  /// ```
  static String ragModelId(String ragId) => '$ragModelPrefix$ragId';

  // ============================================================
  // 6. ЛИМИТЫ СЦЕНАРИЯ document_chat
  // ============================================================

  /// Максимальный размер **одного** файла в `document_chat`.
  ///
  /// Совпадает с лимитом бэкенда: файл больше 25 МБ → `413`.
  /// Проверяем локально, чтобы не гонять зря многомегабайтные запросы.
  static const int documentChatMaxFileSizeBytes = 25 * 1024 * 1024; // 25 МБ

  /// Максимальное количество файлов в **одном сообщении** `document_chat`.
  ///
  /// Бэкендер настраивает через `MAX_ATTACHED_FILES` (1 или 5 в
  /// зависимости от модели). Ставим 5 — если реальный деплой
  /// использует 1, поменяем здесь одно число.
  static const int documentChatMaxAttachedFiles = 5;

  /// Разрешённые MIME-типы для загрузки в `document_chat`.
  ///
  /// Используем для клиентской валидации и для отображения корректного
  /// типа в UI (иконка PDF / превью картинки).
  ///
  /// **ВАЖНО:** MIME не всегда приходит из `file_picker` корректно —
  /// иногда там `application/octet-stream`. Поэтому есть ещё список
  /// расширений ниже, и валидация идёт по обоим.
  static const Set<String> documentChatAllowedMimeTypes = {
    // PDF
    'application/pdf',
    // Изображения (то, что реально поддерживает Android-галерея)
    'image/jpeg',
    'image/jpg',
    'image/png',
  };

  /// Разрешённые расширения файлов для `document_chat`.
  ///
  /// Нужны для `file_picker` — он фильтрует по расширениям, а не по MIME.
  /// Держим синхронно с `documentChatAllowedMimeTypes`: если добавили
  /// MIME — добавьте и расширение, и наоборот.
  static const List<String> documentChatAllowedFileExtensions = [
    'pdf',
    'jpg',
    'jpeg',
    'png',
  ];

  /// Человекочитаемое описание разрешённых форматов `document_chat` —
  /// для сообщений об ошибке.
  static const String documentChatAllowedFormatsDescription = 'PDF, JPG, PNG';

  // ============================================================
  // 7. ЛИМИТЫ СЦЕНАРИЯ RAG
  // ============================================================

  // ---- 7.1. РАЗМЕРЫ И КОЛИЧЕСТВА ----

  /// Максимальный размер **одного** файла в RAG-наборе.
  ///
  /// Бэкенд: **200 МБ** на файл (`INGEST_ARCHIVE_MAX_FILE_SIZE`).
  /// Это **сильно больше**, чем 25 МБ у `document_chat`, поэтому
  /// отдельная константа.
  ///
  /// Проверяем локально, чтобы не гонять зря многомегабайтные запросы.
  static const int ragMaxFileSizeBytes = 200 * 1024 * 1024; // 200 МБ

  /// Максимальное количество файлов в **одной пачке** загрузки в RAG.
  ///
  /// **Это клиентский лимит, не серверный.** Бэкенд **не** устанавливает
  /// максимум на число файлов в одном `POST .../documents`, но
  /// **рекомендует грузить пачками по 5–10**. Причина: загрузка
  /// **не атомарна** — если 5-й файл упал, первые 4 остаются принятыми,
  /// а клиент получает только ошибку без списка.
  ///
  /// Чем меньше пачка — тем понятнее, что успело пройти, и тем проще
  /// перечитать состояние после ошибки.
  static const int ragMaxFilesPerBatch = 10;

  /// Максимальный **суммарный** размер набора (20 ГБ).
  ///
  /// Бэкенд: `INGEST_RAG_MAX_BYTES_PER_SET`. Проверка **накопительная** —
  /// то есть 20 ГБ нельзя превысить и за несколько запросов загрузки.
  ///
  /// На клиенте **не** блокируем по этому лимиту (UI не знает точный
  /// размер уже загруженного), но используем для информирования
  /// в сообщениях об ошибке от бэкенда.
  static const int ragMaxSetSizeBytes = 20 * 1024 * 1024 * 1024; // 20 ГБ

  /// Максимальное количество RAG-наборов на владельца.
  ///
  /// Бэкенд: `INGEST_RAG_MAX_SETS_PER_OWNER = 50`.
  /// При попытке создать 51-й — `409`.
  ///
  /// На клиенте используем для отображения счётчика «X из 50»
  /// и для предупреждения заранее.
  static const int ragMaxSetsPerOwner = 50;

  /// Максимальная длина названия RAG-набора.
  ///
  /// Бэкенд: 1–200 символов (`name` обязателен).
  /// Пустое имя недопустимо — UI валидирует на стороне клиента.
  static const int ragMaxNameLength = 200;

  /// Максимальная длина описания RAG-набора.
  ///
  /// Точного лимита бэкенд не называл. Ставим разумные 2000 —
  /// больше в UI не нужно, а на сервере это TEXT (без ограничения).
  /// Если бэкенд добавит ограничение — поменяем здесь.
  static const int ragMaxDescriptionLength = 2000;

  // ---- 7.2. ФОРМАТЫ ФАЙЛОВ ----

  /// Разрешённые MIME-типы для RAG-документов.
  ///
  /// **Отличается** от `documentChatAllowedMimeTypes`: RAG принимает
  /// текстовые форматы и DOCX, потому что использует docling для
  /// парсинга (а не MinerU для OCR-сканов).
  ///
  /// **Расширяемо:** если бэкенд добавит новые форматы — правка здесь.
  /// Актуальный список всегда в README ingestion-сервиса.
  static const Set<String> ragAllowedMimeTypes = {
    // PDF
    'application/pdf',
    // Word
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document', // .docx
    'application/msword', // .doc (старый формат)
    // Plain text
    'text/plain',
    // Markdown
    'text/markdown',
    'text/x-markdown',
    // Картинки (для документов со сканами)
    'image/jpeg',
    'image/jpg',
    'image/png',
  };

  /// Разрешённые расширения для `file_picker`.
  ///
  /// Держим синхронно с `ragAllowedMimeTypes`.
  static const List<String> ragAllowedFileExtensions = [
    'pdf',
    'docx',
    'doc',
    'txt',
    'md',
    'jpg',
    'jpeg',
    'png',
  ];

  /// Человекочитаемое описание разрешённых форматов RAG.
  static const String ragAllowedFormatsDescription =
      'PDF, DOCX, TXT, MD, JPG, PNG';

  // ---- 7.3. ОПРОС СТАТУСА (POLLING) ----

  /// Интервал опроса статуса RAG-набора.
  ///
  /// Бэкендер рекомендовал **~5 секунд** — rate limit отсутствует,
  /// но чаще не нужно: индексация — тяжёлая операция, статус
  /// меняется не каждую секунду.
  static const Duration ragPollInterval = Duration(seconds: 5);

  /// Максимальное время ожидания готовности RAG-набора.
  ///
  /// **Почему 30 минут:** бэкендер не назвал точный срок индексации.
  /// 30 минут — компромисс: типичные корпуса (10–50 файлов) должны
  /// уложиться. Если реально окажется дольше — увеличим.
  ///
  /// **Зачем таймаут вообще:** чтобы UI не завис навсегда, если на
  /// сервере что-то сломалось и `status` не меняется.
  static const Duration ragPollTimeout = Duration(minutes: 30);

  // ---- 7.4. ИКОНКА НАБОРА ----

  /// Максимальный размер иконки RAG-набора.
  ///
  /// Бэкенд: 512 КБ. Принимаются PNG, JPEG, WebP.
  /// **SVG запрещён** — иконка отдаётся с того же origin, что фронт,
  /// а SVG является исполняемым документом.
  static const int ragIconMaxSizeBytes = 512 * 1024; // 512 КБ

  /// Разрешённые MIME-типы для иконки RAG-набора.
  ///
  /// **Сознательно без SVG** — см. комментарий к `ragIconMaxSizeBytes`.
  static const Set<String> ragIconAllowedMimeTypes = {
    'image/png',
    'image/jpeg',
    'image/jpg',
    'image/webp',
  };

  /// Размер отрисовки иконки при отправке на сервер.
  ///
  /// Пользователь выбирает из **встроенной** библиотеки (SVG-иконки
  /// в `assets/`), а мы рендерим выбранную в PNG нужного размера
  /// и отправляем через `PUT .../icon`.
  ///
  /// 256×256 — компромисс между качеством на Retina-экранах
  /// (x2 = 512 пикселей физических) и размером файла.
  static const int ragIconSize = 256;
}
