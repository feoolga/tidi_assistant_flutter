// lib/core/utils/message_id.dart

/// Value Object для идентификатора сообщения в системе.
///
/// **Проблема, которую он решает.**
///
/// Один и тот же объект (сообщение ассистента) в разных эндпойнтах
/// адресуется разными формами id:
///
/// - `resp_<uuid>` — от Responses API (`POST /v1/responses`,
///   `GET /v1/responses/{id}`);
/// - `msg_<uuid>` — от platform listings
///   (`GET /v1/platform/conversations/{id}/messages`);
/// - голый `<uuid>` — если клиент сохранил id без префикса
///   (например, локально сгенерированный id для pending-сообщения).
///
/// **Важное наблюдение:** у одного и того же сообщения `resp_` и `msg_`
/// формы имеют **один и тот же UUID**. Различается только префикс.
/// Значит, `resp_412a99f2-...` и `msg_412a99f2-...` — это **одно и то же**
/// сообщение, просто по-разному адресуемое.
///
/// **Что это значит для сравнения:** `==` и `hashCode` работают
/// **по UUID без префикса**. Иначе в UI можно было бы получить дубль
/// одного сообщения, пришедшего с разными префиксами.
///
/// **Что это значит для сериализации:** `toString()` возвращает
/// `raw` (как есть, с префиксом). Это то, что уходит в JSON.
///
/// **Почему immutable.** После создания объект нельзя изменить —
/// только создать новый через `asResponse()`/`asMessage()`/`asBare()`.
/// Это исключает баги типа «передали id в чужой контекст и переписали».
///
/// **Почему чистый Dart.** Никаких зависимостей от Flutter, http, JSON.
/// Тестируется без моков.
class MessageId {
  // ============================================================
  // 1. КОНСТАНТЫ ПРЕФИКСОВ
  // ============================================================

  /// Префикс id ответа в Responses API.
  static const String prefixResponse = 'resp_';

  /// Префикс id сообщения в platform listings.
  static const String prefixMessage = 'msg_';

  /// Таблица известных префиксов: `сырая строка` → `канонический префикс`.
  ///
  /// **Почему Map, а не набор `if`-ов.**
  /// - Один источник правды: все префиксы видны в одном месте.
  /// - Легко добавить новый — одна строка.
  /// - Легко тестировать — можно пройтись по всем.
  ///
  /// **Порядок важен.** Более длинные префиксы должны идти раньше,
  /// чтобы `resp_` не матчнулся на гипотетический `r_`. Сейчас
  /// конфликтов нет (`resp_` и `msg_` начинаются с разных букв),
  /// но правило соблюдаем — оно защищает от ошибок в будущем.
  ///
  /// **Почему константа.** Никогда не меняется в рантайме.
  static const Map<String, String> _knownPrefixes = {
    prefixResponse: 'resp',
    prefixMessage: 'msg',
  };

  // ============================================================
  // 2. ПОЛЯ
  // ============================================================

  /// UUID сообщения — **без** префикса, в lower-case.
  ///
  /// Хранится в нормализованном виде: lower-case, с дефисами.
  /// Это «истинное» значение id, по нему сравниваем.
  final String uuid;

  /// Префикс, с которым id пришёл (или был создан).
  ///
  /// `null`, если id — голый UUID без префикса.
  /// Хранится **как есть** — без завершающего `_`, чтобы
  /// не путаться при сравнении.
  final String? prefix;

  // ============================================================
  // 3. ПРИВАТНЫЙ КОНСТРУКТОР
  // ============================================================

  /// Приватный конструктор — создавать только через фабрики.
  ///
  /// Это гарантирует, что `uuid` всегда валидный и в lower-case:
  /// проверка и нормализация — в [parse] и в фабриках `fromXxx`.
  const MessageId._(this.uuid, this.prefix);

  // ============================================================
  // 4. ФАБРИКИ — СОЗДАНИЕ
  // ============================================================

  /// Распарсить id из сырой строки.
  ///
  /// Поддерживает три формы:
  /// - `resp_<uuid>` → `prefix = 'resp'`;
  /// - `msg_<uuid>` → `prefix = 'msg'`;
  /// - `<uuid>` → `prefix = null`.
  ///
  /// Регистр UUID нормализуется к lower-case (RFC 4122 допускает
  /// любой регистр при представлении, но мы храним канонический
  /// lower-case, потому что так делает бэкенд).
  ///
  /// Бросает [ArgumentError], если:
  /// - строка пустая;
  /// - после снятия префикса не остался валидный UUID.
  ///
  /// **Почему бросает:** это ошибка программиста (передали мусор),
  /// а не пользователя. Хотим упасть громко в дебаге.
  factory MessageId.parse(String raw) {
    if (raw.isEmpty) {
      throw ArgumentError.value(raw, 'raw', 'MessageId не может быть пустым');
    }

    // Ищем известный префикс. `_knownPrefixes` — таблица,
    // порядок в ней важен (см. комментарий к таблице).
    String? prefix;
    String uuidPart = raw;

    for (final entry in _knownPrefixes.entries) {
      if (raw.startsWith(entry.key)) {
        prefix = entry.value;
        uuidPart = raw.substring(entry.key.length);
        break; // нашли — выходим, дальше проверять нечего
      }
    }

    // Нормализуем регистр ДО валидации, чтобы `resp_ABC...`
    // тоже принимался.
    final normalized = uuidPart.toLowerCase();

    _validateUuid(normalized, raw);

    return MessageId._(normalized, prefix);
  }

  /// Создать id без префикса (голый UUID).
  ///
  /// Используется, когда id пришёл откуда-то, где префикса нет —
  /// например, из локально сгенерированного id для pending-сообщения.
  factory MessageId.fromUuid(String uuid) {
    final normalized = uuid.toLowerCase();
    _validateUuid(normalized, uuid);
    return MessageId._(normalized, null);
  }

  /// Создать id в форме Responses API: `resp_<uuid>`.
  ///
  /// Принимает UUID **без** префикса. Если передать с префиксом —
  /// упадёт на валидации UUID.
  factory MessageId.fromResponse(String uuid) {
    final normalized = uuid.toLowerCase();
    _validateUuid(normalized, uuid);
    return MessageId._(normalized, 'resp');
  }

  /// Создать id в форме platform message: `msg_<uuid>`.
  factory MessageId.fromMessage(String uuid) {
    final normalized = uuid.toLowerCase();
    _validateUuid(normalized, uuid);
    return MessageId._(normalized, 'msg');
  }

  // ============================================================
  // 5. ВАЛИДАЦИЯ
  // ============================================================

  /// Регулярка для UUID: 8-4-4-4-12 hex-символов (lower-case).
  ///
  /// **Почему не принимаем UPPERCASE:** потому что перед вызовом
  /// [parse] мы уже нормализовали к lower-case. Если сюда пришёл
  /// UPPERCASE — значит, кто-то вызвал фабрику в обход нормализации
  /// (баг в коде), либо это `fromResponse`/`fromMessage`/`fromUuid`,
  /// которые тоже нормализуют. В любом случае — падаем.
  ///
  /// **Почему `static final`, а не `const`:** `RegExp` в Dart
  /// не может быть `const`. `static final` — создаётся один раз
  /// на весь класс, а не на каждый вызов.
  static final RegExp _uuidRegex = RegExp(
    r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$',
  );

  static void _validateUuid(String normalizedUuid, String originalRaw) {
    if (!_uuidRegex.hasMatch(normalizedUuid)) {
      throw ArgumentError.value(
        originalRaw,
        'raw',
        'Некорректный UUID в MessageId. '
            'Ожидается формат 8-4-4-4-12 из hex-символов.',
      );
    }
  }

  // ============================================================
  // 6. ГЕТТЕРЫ — ЧТЕНИЕ
  // ============================================================

  /// Префикс как строка или `null`, если id без префикса.
  ///
  /// Пример: `'resp'`, `'msg'`, `null`.
  String? get prefixOrNull => prefix;

  /// Это id в форме Responses API (`resp_`)?
  bool get isResponse => prefix == 'resp';

  /// Это id в форме platform message (`msg_`)?
  bool get isMessage => prefix == 'msg';

  /// Это голый UUID без префикса?
  bool get isBare => prefix == null;

  /// Полная строка id в **исходном** виде (с префиксом, если был).
  ///
  /// Используется, когда надо отправить id на сервер.
  String get raw {
    if (prefix == null) return uuid;
    // Единственный формат «префикс + разделитель + uuid» — `resp_...`
    // и `msg_...`. Разделитель всегда `_`.
    return '${prefix}_$uuid';
  }

  // ============================================================
  // 7. ПРЕОБРАЗОВАНИЯ
  // ============================================================

  /// Вернуть тот же UUID, но с префиксом `resp_`.
  ///
  /// Используется, когда надо дёрнуть `feedback`/`sources`,
  /// имея id из истории (`msg_...`). Бэкенд принимает любую форму,
  /// но явное приведение к `resp_` — читаемее и защищает от
  /// случайной отправки `msg_` туда, где ожидается `resp_`.
  MessageId asResponse() => MessageId._(uuid, 'resp');

  /// Вернуть тот же UUID, но с префиксом `msg_`.
  MessageId asMessage() => MessageId._(uuid, 'msg');

  /// Вернуть тот же UUID, но без префикса.
  MessageId asBare() => MessageId._(uuid, null);

  // ============================================================
  // 8. РАВЕНСТВО И ХЭШ
  // ============================================================

  /// Сравнение — **по UUID без префикса**.
  ///
  /// **Почему так:** `resp_<uuid>` и `msg_<uuid>` — это **одно и то же**
  /// сообщение. Если бы `==` сравнивал по `raw`, мы бы получили два
  /// разных объекта для одного сообщения — и, например, в UI-списке
  /// могли бы дублироваться.
  ///
  /// Префикс — это **форма адресации**, а не часть идентичности.
  @override
  bool operator ==(Object other) {
    if (identical(this, other)) return true;
    return other is MessageId && other.uuid == uuid;
  }

  /// Хэш — тоже по UUID. Согласовано с [==].
  @override
  int get hashCode => uuid.hashCode;

  // ============================================================
  // 9. СЕРИАЛИЗАЦИЯ
  // ============================================================

  /// Возвращает **исходную** строку (как есть, с префиксом).
  ///
  /// Это то, что удобно логировать и то, что уходит в JSON.
  /// Для сравнения используйте [==] — он по UUID.
  @override
  String toString() => raw;
}
