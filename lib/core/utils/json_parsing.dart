// lib/core/utils/json_parsing.dart

/// Утилиты для **устойчивого** парсинга значений из JSON.
///
/// Зачем нужны:
/// - JSON **нетипизирован** — `json['key']` возвращает `dynamic`,
///   может быть `null`, числом, строкой, чем угодно;
/// - бэкенд **иногда** присылает поля в неожиданных форматах
///   (число вместо строки, `null` в необязательных полях);
/// - прямое `as DateTime` / `as double` **падает** на неожиданных
///   типах, и **весь** ответ теряется из-за **одного** поля.
///
/// **Принцип:** устойчивые функции возвращают `null` при любой
/// проблеме, **не бросают**. `null` значит «не удалось распарсить» —
/// вызывающий код **сам решает**, что делать (fallback, дефолт, падение).
///
/// **Почему функции, а не класс.** Утилиты **без состояния** —
/// идиоматично держать их **глобальными функциями** (как
/// `copyWithUnset` / `isCopyWithUnset` в `copy_with_marker.dart`).
library;

// ============================================================
// 1. ПАРСИНГ ДАТЫ
// ============================================================

/// Устойчивый парсинг даты из JSON.
///
/// Возвращает `DateTime` или `null`:
/// - если значение — **валидная** ISO-8601 строка, парсим её;
/// - если значение — **`null`**, число, пустая строка, невалидный
///   ISO — возвращаем `null` (не бросаем).
///
/// **Почему не бросаем.** Это утилита для **DTO**, а DTO — слой
/// данных. Он должен быть устойчив к неидеальному ответу сервера.
/// «Что делать с плохой датой» — не его ответственность.
/// Маппер (D2) сам решит: fallback (`DateTime.utc(1970, 1, 1)`),
/// дефолт (`DateTime.now()`), или упасть.
///
/// **Почему `dynamic`, а не `Object?`.** `json['key']` возвращает
/// `dynamic` — это **граница** между нетипизированным JSON
/// и типизированным Dart. Здесь `dynamic` **оправдан**.
///
/// Пример:
/// ```dart
/// parseDateOrNull('2026-01-15T10:30:00') // → DateTime(2026, 1, 15, 10, 30)
/// parseDateOrNull(null)                   // → null
/// parseDateOrNull(1735900000)             // → null (число, не строка)
/// parseDateOrNull('вчера')                // → null (не ISO-8601)
/// parseDateOrNull('')                     // → null (пустая строка)
/// ```
DateTime? parseDateOrNull(dynamic value) {
  if (value is String && value.isNotEmpty) {
    try {
      return DateTime.parse(value);
    } on FormatException {
      // Строка есть, но не ISO-8601.
      return null;
    }
  }
  // null, число, пустая строка — невалидные значения.
  return null;
}

// ============================================================
// 2. ПАРСИНГ DOUBLE
// ============================================================

/// Устойчивый парсинг `double` из JSON.
///
/// Возвращает `double` или `null`:
/// - если значение — `double`, возвращаем как есть;
/// - если `int` — приводим к `double` (`1` → `1.0`);
/// - если строка или другое значение — `null`.
///
/// **Почему обрабатываем `int`.** JSON **не различает** `1`
/// и `1.0` — оба «число». Dart при парсинге **может** дать `int`,
/// если сервер прислал `1`. Нам нужен `double`, чтобы не было
/// `TypeError` при `as double?`.
///
/// **Почему не парсим строки.** Если сервер присылает `"0.5"`
/// (строкой) — это **баг контракта**. Хотим **узнать** о нём,
/// а не маскировать.
///
/// Пример:
/// ```dart
/// parseDoubleOrNull(0.5)    // → 0.5
/// parseDoubleOrNull(1)      // → 1.0 (int → double)
/// parseDoubleOrNull(0)      // → 0.0
/// parseDoubleOrNull('0.5')  // → null (строка)
/// parseDoubleOrNull(null)   // → null
/// ```
double? parseDoubleOrNull(dynamic value) {
  if (value is double) return value;
  if (value is int) return value.toDouble();
  return null;
}
