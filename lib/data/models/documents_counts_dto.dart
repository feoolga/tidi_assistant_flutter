// lib/data/models/documents_counts_dto.dart

/// DTO счётчиков документов RAG-набора — **зеркало JSON** от бэкенда.
///
/// Соответствует полю `documents` в ответе
/// `GET /v1/platform/rags/{id}`:
/// ```json
/// "documents": {"total": 3, "ready": 1, "failed": 0, "pending": 2}
/// ```
///
/// **Что такое DTO.** Точное отражение JSON. Не знает про домен,
/// про `DocumentsCounts` (доменный класс).
///
/// **Что делает маппер (D2.4).** Превращает в доменный
/// `DocumentsCounts` с дефолтами.
///
/// **Про обязательность.** Все четыре поля **опциональны** — если
/// сервер не прислал, ставим `0`. Это **правильно**: отсутствие
/// счётчика = «нет документов в этой категории».
///
/// **Про `pending`.** В счётчиках `pending` = «не завершено»
/// (включает и `pending`, и `processing` документы). Это **не**
/// то же самое, что `RagDocumentStatus.pending`. Подробности —
/// в комментарии к доменному `DocumentsCounts`.
class DocumentsCountsDto {
  // ============================================================
  // 1. ПОЛЯ — ТОЧНО КАК В JSON
  // ============================================================

  /// Всего документов в наборе.
  final int total;

  /// Сколько документов **успешно** проиндексировано.
  final int ready;

  /// Сколько документов **упало**.
  final int failed;

  /// Сколько документов **не завершено** (включает `pending`
  /// **и** `processing`).
  final int pending;

  // ============================================================
  // 2. КОНСТРУКТОР
  // ============================================================

  const DocumentsCountsDto({
    this.total = 0,
    this.ready = 0,
    this.failed = 0,
    this.pending = 0,
  });

  // ============================================================
  // 3. ПАРСИНГ ИЗ JSON
  // ============================================================

  /// Создаёт DTO из JSON-объекта `documents`.
  ///
  /// **Все поля — с дефолтом `0`.** Если сервер не прислал —
  /// считаем «0 документов в этой категории». Это **правильно**:
  /// отсутствие счётчика = «ноль», а не «неизвестно».
  ///
  /// **Почему `int?` + `?? 0`, а не `int`.** Если `json['total']`
  /// отсутствует — `as int` упадёт с `TypeError`. А нам **не надо**
  /// падать: счётчики — это **данные для отображения**, не
  /// критичны. Используем `as int? ?? 0`.
  factory DocumentsCountsDto.fromJson(Map<String, dynamic> json) {
    return DocumentsCountsDto(
      total: json['total'] as int? ?? 0,
      ready: json['ready'] as int? ?? 0,
      failed: json['failed'] as int? ?? 0,
      pending: json['pending'] as int? ?? 0,
    );
  }

  // ============================================================
  // 4. ОТЛАДКА
  // ============================================================

  @override
  String toString() =>
      'DocumentsCountsDto(total: $total, ready: $ready, '
      'failed: $failed, pending: $pending)';
}
