// lib/widgets/app_snack_bar.dart

import 'package:flutter/material.dart';

import '../theme/app_theme.dart';

/// Единая точка для показа SnackBar'ов в приложении.
///
/// **Зачем хелпер.**
/// Без него в проекте **десять** мест с `ScaffoldMessenger.of(context)
/// .showSnackBar(...)` — и в каждом **свои** цвета, длительности,
/// префиксы. Это **расползается**: добавляешь новое сообщение —
/// копируешь параметры у соседа, легко ошибиться. Меняешь стиль —
/// нужно пройти по **всем** местам.
///
/// **Что делает.** Сводит **все** показы к **двум** семантическим
/// типам:
/// - [showError] — ошибка (красный, крестик, не исчезает);
/// - [showInfo] — информация (Тиффани, исчезает через 3 секунды).
///
/// **Что НЕ делает.** Не решает, **какой** тип использовать —
/// это ответственность вызывающего кода. Не логирует — это
/// `AppLogger`. Не обрабатывает ошибки — это `ErrorHandler`.
///
/// **Как использовать:**
/// ```dart
/// AppSnackBar.showError(context, 'Не удалось загрузить файл');
/// AppSnackBar.showInfo(context, 'Файл прикреплён');
/// ```
class AppSnackBar {
  /// Приватный конструктор — класс используется только статически.
  const AppSnackBar._();

  /// Показать **ошибку**.
  ///
  /// **Поведение:**
  /// - красный фон;
  /// - иконка `❌` перед текстом;
  /// - **крестик** в углу — пользователь закроет **сам**;
  /// - **не исчезает** автоматически (`duration: 1 день` —
  ///   фактически «висит до закрытия»).
  ///
  /// **Почему не исчезает.** Пользователь **не ожидал** ошибки —
  /// мог **отвлечься**, **не смотреть** на экран, **чихнуть**.
  /// Если сообщение исчезнет через 3 секунды — он **не поймёт**,
  /// что произошло. Крестик даёт **контроль**: пользователь
  /// **сам** решает, когда прочитал.
  ///
  /// **Почему `duration: 1 день`, а не «бесконечность».** У Flutter
  /// **нет** «бесконечного» SnackBar. `Duration(days: 1)` — **настолько
  /// долго**, что фактически «вечно» для пользователя. Не мешает
  /// **очереди** других SnackBar'ов — можно показать **новый** поверх.
  static void showError(BuildContext context, String message) {
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text('❌ $message'),
        backgroundColor: Colors.red,
        // Крестик в углу — пользователь закроет сам.
        // `SnackBar` с `showCloseIcon: true` сам обрабатывает нажатие.
        showCloseIcon: true,
        // «Вечно» — фактически. См. комментарий выше.
        duration: const Duration(days: 1),
      ),
    );
  }

  /// Показать **информационное** сообщение.
  ///
  /// **Поведение:**
  /// - фон — основной цвет (Тиффани);
  /// - иконка `ℹ️` перед текстом;
  /// - **без** крестика;
  /// - исчезает через **3 секунды**.
  ///
  /// **Когда использовать.** Подтверждения («Чат переименован»),
  /// нейтральные подсказки («Дождитесь загрузки файлов»), **не**
  /// критические сообщения. Пользователь **сам** инициировал действие,
  /// **смотрит** на экран, **увидит** сообщение **вовремя**.
  ///
  /// **Почему не «висит».** Информация **не требует** действия —
  /// через 3 секунды **неактуальна**. Занимать экран дольше —
  /// **мешать** пользователю.
  static void showInfo(BuildContext context, String message) {
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text('ℹ️ $message'),
        backgroundColor: AppTheme.primary,
        duration: const Duration(seconds: 3),
      ),
    );
  }
}
